"""
Generate Finnish audio for every word, sentence, story line and character
intro, then write src/audio/manifest.ts so the app plays the clips instead of
the device's robotic text-to-speech voice.

Two engines:

  edge  (default)  Microsoft's neural voices through the `edge-tts` package.
                   Two Finnish base voices (Noora, Harri); each character gets
                   its own pitch and pace from characters.json, so the cast
                   sounds like seven different people. Needs internet. Writes
                   mp3 directly, no ffmpeg needed.
                   NOTE: edge-tts uses the read-aloud service built into the
                   Edge browser. It is free, but it is not an official API and
                   Microsoft's terms for redistributing the output are not
                   clear. Fine for development and testing. Check the terms, or
                   switch to Piper, before a public release.

  piper            Piper TTS: open source, offline, clearly licensed, but only
                   one Finnish voice (Harri), so all characters sound alike.

Setup:
    pip install edge-tts
    # or, for piper:
    pip install piper-tts
    python -m piper.download_voices fi_FI-harri-medium --data-dir voices

Run:
    python scripts/generate_audio.py                 # only missing clips
    python scripts/generate_audio.py --force         # regenerate everything
    python scripts/generate_audio.py --engine piper  # offline, single voice
    python scripts/generate_audio.py --manifest-only
"""
import argparse
import asyncio
import shutil
import subprocess
import sys
import wave
from pathlib import Path

from common import AUDIO_DIR, ROOT, load_characters, speakable_items

MANIFEST = ROOT / "src" / "audio" / "manifest.ts"

EDGE_VOICES = {"noora": "fi-FI-NooraNeural", "harri": "fi-FI-HarriNeural"}
# Words and other speaker-less items are read by a neutral narrator
NARRATOR = {"base": "noora", "pitch": "+0Hz", "rate": "-4%"}


def write_manifest():
    clips = sorted(p for p in AUDIO_DIR.iterdir() if p.suffix in {".wav", ".mp3"})
    lines = [
        "// AUTO-GENERATED by scripts/generate_audio.py. Do not edit by hand.",
        "export const AUDIO: Record<string, number> = {",
    ]
    for p in clips:
        lines.append(f'  "{p.stem}": require("../../assets/audio/{p.name}"),')
    lines.append("};")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Manifest: {len(clips)} clips -> {MANIFEST.relative_to(ROOT)}")


def todo(force):
    for audio_id, text, speaker in speakable_items():
        if not force and any((AUDIO_DIR / f"{audio_id}{ext}").exists() for ext in (".mp3", ".wav")):
            continue
        yield audio_id, text, speaker


def run_edge(force):
    try:
        import edge_tts
    except ImportError:
        sys.exit("edge-tts is not installed: pip install edge-tts")

    voices = {c["id"]: c["voice"] for c in load_characters()}
    jobs = list(todo(force))
    failed = []
    sem = None  # made inside the event loop: older Pythons bind a semaphore to the loop it was created in

    async def one(audio_id, text, speaker):
        v = voices.get(speaker, NARRATOR)
        out = AUDIO_DIR / f"{audio_id}.mp3"
        async with sem:
            err = None
            for attempt in range(3):
                try:
                    await edge_tts.Communicate(text, EDGE_VOICES[v["base"]], rate=v["rate"], pitch=v["pitch"]).save(str(out))
                    if out.stat().st_size > 0:
                        return
                except Exception as e:  # network hiccups: retry, then report
                    err = e
                    await asyncio.sleep(1 + attempt)
            if out.exists():
                out.unlink()
            failed.append((audio_id, str(err)))

    async def main():
        nonlocal sem
        sem = asyncio.Semaphore(6)
        await asyncio.gather(*(one(*j) for j in jobs))

    asyncio.run(main())
    print(f"Generated {len(jobs) - len(failed)} clips with edge-tts.")
    for audio_id, err in failed:
        print(f"FAILED {audio_id}: {err}")
    return not failed


def run_piper(force, voice_path, mp3):
    try:
        from piper import PiperVoice
    except ImportError:
        sys.exit("piper-tts is not installed: pip install piper-tts")
    if not Path(voice_path).exists():
        sys.exit(f"Voice model not found at {voice_path}. See the setup notes at the top of this file.")
    ffmpeg = shutil.which("ffmpeg") if mp3 else None
    if mp3 and not ffmpeg:
        print("ffmpeg not found, keeping .wav files")
    voice = PiperVoice.load(voice_path)
    made = 0
    for audio_id, text, _speaker in todo(force):
        wav = AUDIO_DIR / f"{audio_id}.wav"
        with wave.open(str(wav), "wb") as wf:
            if hasattr(voice, "synthesize_wav"):  # piper-tts >= 1.3
                voice.synthesize_wav(text, wf)
            else:
                voice.synthesize(text, wf)
        if ffmpeg:
            subprocess.run([ffmpeg, "-y", "-loglevel", "error", "-i", str(wav), "-b:a", "64k", str(wav.with_suffix(".mp3"))], check=True)
            wav.unlink()
        made += 1
    print(f"Generated {made} clips with Piper.")
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", choices=["edge", "piper"], default="edge")
    ap.add_argument("--voice", default=str(ROOT / "voices" / "fi_FI-harri-medium.onnx"), help="Piper voice model")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--mp3", action="store_true", help="Piper only: convert clips to mp3 via ffmpeg")
    ap.add_argument("--manifest-only", action="store_true")
    args = ap.parse_args()

    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    ok = True
    if not args.manifest_only:
        ok = run_edge(args.force) if args.engine == "edge" else run_piper(args.force, args.voice, args.mp3)
    write_manifest()
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
